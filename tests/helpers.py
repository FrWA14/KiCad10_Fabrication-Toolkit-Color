def parse_matrix(transform):
    m = re.fullmatch(r"\s*matrix\(([^)]*)\)\s*", transform)
    return [float(v) for v in m.group(1).split()]


def image_placement(svg_text):
    """Return (x0, x1, y0, y1) of the embedded image in the root SVG frame,
    applying the image matrix and the parent group transform."""
    root = ET.fromstring(svg_text.encode("utf-8"))
    g = root.find("svg:g", SVG_NS)
    img = g.find("svg:image", SVG_NS)
    a, b, c, d, e, f = parse_matrix(img.get("transform"))
    w, h = float(img.get("width")), float(img.get("height"))
    corners = [(a * x + c * y + e, b * x + d * y + f) for x, y in ((0, 0), (w, 0), (0, h), (w, h))]
    gt = g.get("transform")
    m = re.fullmatch(r"scale\((\S+) (\S+)\) translate\((\S+) (\S+)\)", gt)
    sx, sy, tx, ty = (float(v) for v in m.groups())
    # SVG applies the rightmost transform first: translate, then scale.
    corners = [((x + tx) * sx, (y + ty) * sy) for x, y in corners]
    xs = [p[0] for p in corners]
    ys = [p[1] for p in corners]
    return min(xs), max(xs), min(ys), max(ys), sx < 0, a < 0
